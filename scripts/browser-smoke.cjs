/* Integration checks in a fresh Chromium profile, without user credentials. */
const {chromium}=require('playwright-core');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
(async()=>{
 const profile=await fs.mkdtemp(path.join(os.tmpdir(),'karmdown-qa-'));
 const root=path.resolve(__dirname,'..');
 const options={headless:!process.env.KARMDOWN_HEADED,args:[`--disable-extensions-except=${root}`,`--load-extension=${root}`]};
 if(process.env.KARMDOWN_CHROMIUM) options.executablePath=process.env.KARMDOWN_CHROMIUM;
 const context=await chromium.launchPersistentContext(profile,options);
 const http=require('node:http');
 const server=http.createServer((req,res)=>{res.setHeader('Content-Type',req.url==='/page.md'?'text/html':'text/plain');res.end(req.url==='/page.md'?'<html><body><h1>Normal website</h1><pre># Example</pre></body></html>':'# Remote Markdown\n\nOnly after an explicit command.');});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin='http://127.0.0.1:'+server.address().port;
 try {
 const worker=context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
 const id=new URL(worker.url()).host;
 const page=await context.newPage(); const errors=[]; const requests=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(r.url()));
 let fixture=await fs.readFile(path.join(root,'tests/fixture.md'),'utf8');
 await fs.copyFile(path.join(root,'icons/icon128.png'),path.join(profile,'actual.png'));
 await fs.writeFile(path.join(profile,'not-image.txt'),'SYNTHETIC_NON_IMAGE_MUST_NOT_EXPORT');
 fixture+='\n![Local icon](actual.png)\n\n![Blocked file](not-image.txt)\n';
 const file=path.join(profile,'demo.md');await fs.writeFile(file,fixture);
 await page.goto('file://'+file);
 await page.locator('.mv-meta').waitFor();
 await page.locator('.mv-mermaid svg').waitFor();await page.locator('.katex').first().waitFor();await page.locator('.hljs').waitFor();
 assert.equal(await page.locator('html').getAttribute('lang'),'en');
 assert.equal(await page.evaluate(()=>window.KD_XSS),undefined);
 assert.equal(requests.some(url=>url.startsWith('https://example.com/tracker')),false);
 assert.equal(await page.locator('.mv-doc script,.mv-doc [onerror],.mv-doc a[href^="javascript:"]').count(),0);
 assert.match(await page.locator('.hljs').innerText(),/\$not_math\$/);
 await page.waitForFunction(()=>document.querySelector('.mv-doc img')?.naturalWidth===128);
 assert.equal(await page.locator('.mv-doc img').count(),1);
 console.log('PASS local file, isolated libraries, math/code separation, XSS, remote image blocking');
 await page.getByRole('button',{name:'Find',exact:true}).click();
 await page.getByRole('searchbox').fill('Markdown');
 assert.ok(await page.locator('mark.mv-found').count()>=4);
 await page.getByRole('searchbox').press('Enter');
 assert.match(await page.locator('.mv-match-count').innerText(),/^2 \/ /);
 await page.keyboard.press('Escape');assert.equal(await page.locator('mark.mv-found').count(),0);
 console.log('PASS rendered-text search, next match, Escape');
 // Watcher refreshes clean documents, but protects edits when the file changes again.
 await fs.writeFile(file,fixture+'\n## Disk update\n');
 await page.getByRole('heading',{name:'Disk update',exact:true}).waitFor({timeout:10000});
 await page.getByRole('button',{name:'Split',exact:true}).click();
 const editor=page.locator('#mv-editor');await editor.fill(fixture+'\n## Private draft\n');
 await page.getByRole('heading',{name:'Private draft',exact:true}).waitFor();
 await fs.writeFile(file,fixture+'\n## New disk version\n');
 await page.locator('.mv-reload:not([hidden])').waitFor({timeout:10000});
 assert.match(await editor.inputValue(),/Private draft/);
 await page.getByRole('button',{name:'Load disk version',exact:true}).click();
 await page.getByRole('heading',{name:'New disk version',exact:true}).waitFor();
 console.log('PASS live reload and draft conflict protection');
 // Popup settings reach the already-open viewer, and Russian remains usable.
 const popup=await context.newPage();await popup.goto(`chrome-extension://${id}/popup.html`);
 await popup.locator('#lang').selectOption('ru');await page.waitForFunction(()=>document.documentElement.lang==='ru');
 assert.equal(await page.getByRole('button',{name:'Поиск',exact:true}).count(),1);
 await popup.locator('#lang').selectOption('en');
 await popup.locator('#theme').selectOption('dark');await page.waitForFunction(()=>document.querySelector('#mv-root').dataset.theme==='dark');
 await popup.locator('#theme').selectOption('light');await popup.close();await page.bringToFront();
 console.log('PASS English default, Russian, live popup settings');
 await page.getByRole('button',{name:'Preview',exact:true}).click();
 const downloadWait=page.waitForEvent('download');await page.getByRole('button',{name:'Export HTML',exact:true}).click();
 const download=await downloadWait;const exported=await fs.readFile(await download.path(),'utf8');
 assert.match(exported,/data:application\/|data:font\//);assert.match(exported,/<svg/);
 assert.equal(exported.includes(Buffer.from('SYNTHETIC_NON_IMAGE_MUST_NOT_EXPORT').toString('base64')),false);
 assert.equal(/<img[^>]+src="data:image\/png;base64,/.test(exported),true,'Local image must be embedded');
 assert.equal(/<script|chrome-extension:|file:\/\//.test(exported),false,'Export must not contain scripts or extension/local URLs');
 const exportedPage=await context.newPage();await exportedPage.setContent(exported);assert.equal(await exportedPage.locator('.katex').count(),2);assert.equal(await exportedPage.locator('.mv-search,mark.mv-found,button').count(),0);await exportedPage.close();
 await page.emulateMedia({media:'print'});
 assert.equal(await page.locator('.mv-bar').isVisible(),false);assert.equal(await page.locator('.mv-toc').isVisible(),false);
 assert.equal(await page.locator('.mv-doc').isVisible(),true);
 await page.pdf({path:path.join(profile,'print.pdf')});await page.emulateMedia({media:'screen'});
 console.log('PASS standalone HTML, embedded math fonts/diagram, clean PDF layout');
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.locator('.mv-bar').isVisible());
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
 console.log('PASS narrow viewport');
 // File picker starts a separate document and disables the original file watcher.
 await page.locator('.mv-file-input').setInputFiles(path.join(root,'tests/fixture.md'));
 assert.equal(await page.locator('.mv-file').textContent(),'fixture.md');
 await page.waitForTimeout(2400);assert.equal(await page.locator('.mv-reload').isVisible(),false);
 console.log('PASS file import without stale file watcher');
 await page.getByRole('button',{name:'Editor',exact:true}).click();
 await page.locator('#mv-editor').fill(fixture+'\n## Imported draft\n');await page.waitForTimeout(900);
 await page.locator('.mv-file-input').setInputFiles(path.join(root,'tests/fixture.md'));
 await page.locator('.mv-banner.show').waitFor({timeout:2000});
 await page.getByRole('button',{name:'Restore draft',exact:true}).click();
 assert.match(await page.locator('#mv-editor').inputValue(),/Imported draft/);
 console.log('PASS imported file draft recovery');
 const remote=await context.newPage();await remote.goto(origin+'/remote.md');
 assert.equal(await remote.locator('#mv-root').count(),0);
 await remote.goto(origin+'/page.md');await remote.waitForTimeout(300);
 assert.equal(await remote.locator('#mv-root').count(),0);await remote.close();
 console.log('PASS remote pages never auto-activate; ordinary HTML untouched');
 console.log('NOTE: physical Alt+Shift+M command requires owner Chrome check; synthetic Playwright keys do not invoke browser extension commands.');
 assert.deepEqual(errors,[]);
 console.log('Browser smoke passed.');
 } finally {server.close();await context.close();await fs.rm(profile,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
